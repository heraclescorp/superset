API_SUFFIXES = frozenset({"success", "warning", "error", "time", "ok"})

_MCP_TOOLS = frozenset({"unknown", "call_tool"})
_MCP_LOCK = threading.Lock()


def register_mcp_tools(names: Iterable[str]) -> None:
    """Register only names confirmed by FastMCP's actual tool registry.

    Callers must not pass raw client tool strings or regex-only fallbacks. The
    registry remains finite even if an operator loads many extensions; native
    metric series have a separate overflow aggregation bound.
    """
    global _MCP_TOOLS
    for name in names:
        if (
            not isinstance(name, str)
            or not re.fullmatch(r"[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}", name)
            or name in _MCP_TOOLS
        ):
            continue
        with _MCP_LOCK:
            if len(_MCP_TOOLS) < 1026:
                _MCP_TOOLS = _MCP_TOOLS | {name}


def _after_fork() -> None:
    global _MCP_LOCK
    _MCP_LOCK = threading.Lock()


if hasattr(os, "register_at_fork"):
    os.register_at_fork(after_in_child=_after_fork)


def canonical_legacy_key(key: object) -> str:
    """Accept only a static key or a finite built-in REST API key family."""
    if not isinstance(key, str):
        return "other"
    if key in LITERAL_KEYS:
        return key
    if key.startswith("mcp.tool."):
        tool, separator, outcome = key[len("mcp.tool.") :].rpartition(".")
        if (
            separator
            and tool in _MCP_TOOLS
            and outcome in {"success", "warning", "error", "time"}
        ):
            return key
    parts = key.split(".")
    if (
        len(parts) == 3
        and parts[0] in API_CLASSES
        and parts[1] in API_METHODS
        and parts[2] in API_SUFFIXES
    ):
        return key
    return "other"
